"use client";

import { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import PaymentMethodModal from "@/components/payment-method-modal";
import { FontAwesomeIcon } from "@fortawesome/react-fontawesome";
import {
  faChevronLeft,
  faCircleExclamation,
  faSpinner,
} from "@fortawesome/free-solid-svg-icons";
import { format } from "date-fns";
import { getSessionSource, track } from "@/lib/analytics";

// Declare PaystackPop globally
declare global {
  interface Window {
    PaystackPop: any;
  }
}

interface CartItem {
  id: string;
  name: string;
  price: number;
  quantity: number;
}

interface SavedCart {
  items: CartItem[];
  visitDate: string | null;
  totalAmount: number;
}

export default function DayPassCheckout() {
  const router = useRouter();
  const [cart, setCart] = useState<SavedCart>({
    items: [],
    visitDate: null,
    totalAmount: 0,
  });
  const [loading, setLoading] = useState(true);
  const [processing, setProcessing] = useState(false);
  const [email, setEmail] = useState("");
  const [phone, setPhone] = useState("");
  const [fullName, setFullName] = useState("");
  const [error, setError] = useState("");
  const [showPaymentMethodModal, setShowPaymentMethodModal] = useState(false);
  const [pendingBooking, setPendingBooking] = useState<any>(null);

  // Load cart from localStorage
  useEffect(() => {
    if (typeof window !== "undefined") {
      const savedCart = localStorage.getItem("dayPassCart");
      if (savedCart) {
        try {
          const parsedCart = JSON.parse(savedCart);
          setCart(parsedCart);
        } catch (err) {
          console.error("Failed to load cart:", err);
          setError("Failed to load cart");
        }
      }
      setLoading(false);
    }
  }, []);

  // Check if cart is empty
  useEffect(() => {
    if (!loading && cart.items.length === 0) {
      router.push("/day-pass/cart");
    }
  }, [loading, cart.items.length, router]);

  const paystackKey = process.env.NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY;
  const isValidPaystackKey =
    paystackKey &&
    paystackKey !== "pk_test_xxxxxxxxxxxx" &&
    paystackKey.startsWith("pk_");

  const handleOpenPaymentMethod = async (e: React.FormEvent) => {
    e.preventDefault();

    if (!fullName || !email || !phone) {
      setError("Please fill in all fields");
      return;
    }

    if (!cart.visitDate) {
      setError("Please select a visit date");
      return;
    }

    // Verify user has at least one valid ticket (any ticket except Infant alone)
    // Valid tickets: Items with "Ticket" in the name, excluding Infant Ticket
    const hasValidTicket = cart.items.some(
      (item) => item.name.includes("Ticket") && !item.name.includes("Infant"),
    );

    if (!hasValidTicket) {
      setError(
        "You must select at least one ticket (Day Pass or Premium ticket). Add-on experiences alone cannot be booked.",
      );
      return;
    }

    // Verify infant tickets have a valid companion ticket
    const hasInfant = cart.items.some((item) =>
      item.name.includes("Infant Ticket"),
    );
    if (hasInfant && !hasValidTicket) {
      setError(
        "Infant tickets must be accompanied by at least one ticketed guest (Kids, Teens, or Adult).",
      );
      return;
    }

    setProcessing(true);
    setError("");

    try {
      // Create day-pass booking
      const bookingRes = await fetch("/api/day-pass/create", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          fullName,
          email,
          phone,
          visitDate: cart.visitDate,
          items: cart.items,
          totalAmount: cart.totalAmount,
          source: getSessionSource(),
        }),
      });

      if (!bookingRes.ok) {
        const errorData = await bookingRes.json();
        throw new Error(errorData.error || "Failed to create booking");
      }

      const bookingData = await bookingRes.json();
      track("daypass_payment_start", { amount: Number(bookingData.totalAmount) || 0 });
      setPendingBooking(bookingData);
      setShowPaymentMethodModal(true);
      setProcessing(false);
    } catch (err: any) {
      setError(err.message || "Failed to create booking");
      setProcessing(false);
    }
  };

  const handlePaystackPayment = async () => {
    if (!pendingBooking) return;

    setProcessing(true);
    setShowPaymentMethodModal(false);

    try {
      // Use the Paystack reference generated by the API, not a locally-generated one
      const paystackRef = pendingBooking.paystackReference;

      if (!isValidPaystackKey) {
        // Demo mode (no live Paystack key configured)
        await new Promise((resolve) => setTimeout(resolve, 2000));

        try {
          const confirmRes = await fetch("/api/day-pass/confirm-payment", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              bookingId: pendingBooking.id,
              reference: paystackRef,
            }),
          });

          if (!confirmRes.ok) {
            const errData = await confirmRes.json().catch(() => ({}));
            throw new Error(
              errData.error || "Payment could not be verified",
            );
          }
        } catch (err: any) {
          setError(
            err.message ||
              "We couldn't confirm your payment. Please contact support with your reference.",
          );
          setProcessing(false);
          return;
        }

        track("daypass_paid", { amount: Number(pendingBooking.totalAmount) || 0 });
        if (typeof window !== "undefined") {
          localStorage.removeItem("dayPassCart");
          localStorage.setItem("lastOrderCompleted", Date.now().toString());
          window.dispatchEvent(new Event("cart-updated"));
        }

        // Client-side navigation — instant, no full-page reload flash.
        router.push(
          `/day-pass/confirmation?bookingId=${pendingBooking.id}&ref=${paystackRef}`,
        );
        return;
      }

      // Real Paystack payment
      //
      // NOTE: when the Paystack script has to be loaded for the first time,
      // this function runs from script.onload — which fires *after*
      // handlePaystackPayment's own try/catch has already returned. Any
      // exception thrown in here would otherwise be an uncaught error that
      // leaves the UI stuck on "Processing..." forever (no popup, no error
      // message), so it needs its own try/catch rather than relying on the
      // outer one.
      const openPaystackCheckout = () => {
        try {
          openPaystackCheckoutUnsafe();
        } catch (err: any) {
          console.error("Failed to open Paystack checkout:", err);
          setError(
            err?.message || "Failed to open payment window. Please try again.",
          );
          setProcessing(false);
        }
      };

      const openPaystackCheckoutUnsafe = () => {
        if (!window.PaystackPop) {
          setError("Failed to load payment provider. Please try again.");
          setProcessing(false);
          return;
        }

        // Guards against onSuccess/onClose both firing (or firing more than once)
        let resolved = false;

        const handlePaymentSuccess = async (response: any) => {
          if (resolved) return;
          resolved = true;

          // Get the actual Paystack reference from the response
          const actualPaystackReference = response.reference || paystackRef;

          // Verify with the server BEFORE showing the receipt or clearing the cart —
          // never assume success just because Paystack's client-side callback fired
          try {
            const confirmRes = await fetch("/api/day-pass/confirm-payment", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                bookingId: pendingBooking.id,
                reference: actualPaystackReference,
              }),
            });

            if (!confirmRes.ok) {
              const errData = await confirmRes.json().catch(() => ({}));
              throw new Error(
                errData.error ||
                  "We couldn't verify your payment yet. If you were charged, please contact support with your reference.",
              );
            }
          } catch (err: any) {
            setError(
              err.message ||
                "We couldn't verify your payment. Please contact support.",
            );
            setProcessing(false);
            return;
          }

          // Only clear the cart and show the receipt once verification succeeds
          track("daypass_paid", { amount: Number(pendingBooking.totalAmount) || 0 });
          if (typeof window !== "undefined") {
            localStorage.removeItem("dayPassCart");
            window.dispatchEvent(new Event("cart-updated"));
          }

          // Go straight to the receipt — no intermediate "click to view" step,
          // and a client-side navigation so there's no full-page reload flash.
          clearTimeout(stuckTimer);
          router.push(
            `/day-pass/confirmation?bookingId=${pendingBooking.id}&ref=${actualPaystackReference}`,
          );
        };

        const handler = window.PaystackPop.setup({
          key: paystackKey,
          email: email,
          amount: Math.round(Number(pendingBooking.totalAmount ?? cart.totalAmount) * 100),
          ref: paystackRef,
          // The classic PaystackPop.setup() global script (js.paystack.co/v1/inline.js)
          // only recognizes "callback" for the success handler — "onSuccess" is a
          // different API surface (the @paystack/inline-js npm package's class-based
          // PaystackPop) and is silently ignored here, which is why this never fired.
          //
          // Must be a plain (non-async) function: Paystack's validator checks
          // Object.prototype.toString.call(fn) === "[object Function]", which
          // an async function fails (it reports "[object AsyncFunction]"),
          // so passing handlePaymentSuccess directly throws "Attribute
          // callback must be a valid function" before the popup ever opens.
          callback: (response: any) => {
            handlePaymentSuccess(response);
          },
          onClose: () => {
            if (resolved) return;
            resolved = true;
            clearTimeout(stuckTimer);
            setError("Payment cancelled");
            setProcessing(false);
          },
        });
        handler.openIframe();

        // Safety net: if Paystack never calls back at all (e.g. its iframe
        // silently fails to load), recover the UI to an error state after a
        // generous wait rather than leaving "Processing..." stuck forever.
        // This never assumes success — only onSuccess (verified server-side
        // above) can do that.
        const stuckTimer = setTimeout(() => {
          if (resolved) return;
          resolved = true;
          setError(
            "The payment window didn't respond. Please try again — if you were charged, contact support with your booking reference.",
          );
          setProcessing(false);
        }, 90_000);
      };

      if (typeof window !== "undefined" && window.PaystackPop) {
        openPaystackCheckout();
      } else {
        // Load Paystack script, then open the checkout once it's ready
        const script = document.createElement("script");
        script.src = "https://js.paystack.co/v1/inline.js";
        script.async = true;
        script.onload = openPaystackCheckout;
        script.onerror = () => {
          setError("Failed to load payment provider. Please try again.");
          setProcessing(false);
        };
        document.head.appendChild(script);
      }
    } catch (err: any) {
      setError(err.message || "Payment failed");
      setProcessing(false);
    }
  };

  const handleZibaPayment = () => {
    if (!pendingBooking) return;

    const visitDate = format(new Date(cart.visitDate!), "MMM dd, yyyy");
    const itemsList = cart.items
      .map((item) => `- ${item.name} ×${item.quantity}`)
      .join("\n");
    const message = `Hi Ziba Resort! 👋\n\nI would like to make a booking payment.\n\n📋 *Booking Details:*\n- Guest: ${fullName}\n- Visit Date: ${visitDate}\n- Items:\n${itemsList}\n- Total Amount: ₦${cart.totalAmount.toLocaleString()}\n- Phone: ${phone}\n\nPlease confirm the payment options available. Thank you!`;

    const whatsappUrl = `https://wa.me/+2347047300013?text=${encodeURIComponent(message)}`;

    setShowPaymentMethodModal(false);
    track("whatsapp_click", { context: "daypass-payment" });
    window.open(whatsappUrl, "_blank");
    setProcessing(false);
  };

  if (loading) {
    return (
      <main className="min-h-screen bg-linear-to-b from-blue-50 to-white flex items-center justify-center px-4">
        <div className="text-center">
          <FontAwesomeIcon icon={faSpinner} className="w-12 h-12 text-blue-900 animate-spin mx-auto mb-4" />
          <p className="text-gray-600">Loading...</p>
        </div>
      </main>
    );
  }

  return (
    <>
      <main className="min-h-screen bg-linear-to-b from-blue-50 to-white py-8 px-4">
        <div className="max-w-2xl mx-auto">
          {/* Back Button */}
          <button
            onClick={() => router.back()}
            className="mb-6 flex items-center gap-2 text-blue-900 hover:text-blue-800 transition-colors"
          >
            <FontAwesomeIcon icon={faChevronLeft} className="w-5 h-5" />
            <span className="font-medium">Back</span>
          </button>

          <div className="grid md:grid-cols-3 gap-6">
            {/* Checkout Form */}
            <div className="md:col-span-2 space-y-6">
              {/* Guest Information */}
              <div className="bg-white rounded-lg shadow-md p-6">
                <h2 className="text-xl font-bold text-gray-900 mb-4">
                  Your Information
                </h2>

                {error && (
                  <div className="bg-red-50 border border-red-200 text-red-700 px-4 py-3 rounded-lg mb-4 flex items-start gap-3">
                    <FontAwesomeIcon icon={faCircleExclamation} className="w-5 h-5 mt-0.5 shrink-0" />
                    <span>{error}</span>
                  </div>
                )}

                <form onSubmit={handleOpenPaymentMethod} className="space-y-4">
                  <div>
                    <label className="block text-sm font-medium text-gray-700 mb-2">
                      Full Name *
                    </label>
                    <input
                      type="text"
                      value={fullName}
                      onChange={(e) => setFullName(e.target.value)}
                      placeholder="John Doe"
                      className="w-full px-4 py-2 border-2 border-gray-300 rounded-lg focus:border-blue-900 focus:outline-none"
                    />
                  </div>

                  <div>
                    <label className="block text-sm font-medium text-gray-700 mb-2">
                      Email *
                    </label>
                    <input
                      type="email"
                      value={email}
                      onChange={(e) => setEmail(e.target.value)}
                      placeholder="john@example.com"
                      className="w-full px-4 py-2 border-2 border-gray-300 rounded-lg focus:border-blue-900 focus:outline-none"
                    />
                  </div>

                  <div>
                    <label className="block text-sm font-medium text-gray-700 mb-2">
                      Phone *
                    </label>
                    <input
                      type="tel"
                      value={phone}
                      onChange={(e) => setPhone(e.target.value)}
                      placeholder="+234 700 000 0000"
                      className="w-full px-4 py-2 border-2 border-gray-300 rounded-lg focus:border-blue-900 focus:outline-none"
                    />
                  </div>

                  <button
                    type="submit"
                    disabled={processing}
                    className="w-full bg-blue-900 hover:bg-blue-800 disabled:opacity-50 text-white font-bold py-3 rounded-lg transition-colors"
                  >
                    {processing ? "Processing..." : "Make Payment"}
                  </button>
                </form>
              </div>
            </div>

            {/* Order Summary */}
            <div className="md:col-span-1">
              <div className="bg-white rounded-lg shadow-md p-6 sticky top-8">
                <h2 className="text-xl font-bold text-gray-900 mb-4">
                  Order Summary
                </h2>

                <div className="space-y-3 mb-4">
                  <div className="flex justify-between text-sm">
                    <span className="text-gray-600">Visit Date:</span>
                    <span className="font-semibold">
                      {format(new Date(cart.visitDate!), "MMM d, yyyy")}
                    </span>
                  </div>
                  <div className="flex justify-between text-sm">
                    <span className="text-gray-600">Items:</span>
                    <span className="font-semibold">
                      {cart.items.reduce((sum, item) => sum + item.quantity, 0)}
                    </span>
                  </div>
                </div>

                <div className="border-t border-gray-200 pt-4 mb-4">
                  <div className="flex justify-between mb-2">
                    <span className="text-gray-600">Subtotal:</span>
                    <span className="font-semibold">
                      ₦{cart.totalAmount.toLocaleString()}
                    </span>
                  </div>
                  <div className="flex justify-between text-lg font-bold">
                    <span>Total:</span>
                    <span className="text-blue-700">
                      ₦{cart.totalAmount.toLocaleString()}
                    </span>
                  </div>
                </div>

                <div className="bg-blue-50 rounded-lg p-3 text-xs text-blue-900">
                  <p className="font-semibold mb-2">Items:</p>
                  <ul className="space-y-1">
                    {cart.items.map((item) => (
                      <li key={item.id} className="flex justify-between">
                        <span>{item.name}</span>
                        <span>×{item.quantity}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              </div>
            </div>
          </div>
        </div>
      </main>

      {/* Payment Method Modal */}
      <PaymentMethodModal
        isOpen={showPaymentMethodModal}
        onClose={() => setShowPaymentMethodModal(false)}
        onPaystackClick={handlePaystackPayment}
        onWhatsAppClick={handleZibaPayment}
        roomName={cart.items.length > 0 ? "Day Experience Pass" : ""}
        totalAmount={cart.totalAmount}
        checkInDate={
          cart.visitDate ? format(new Date(cart.visitDate), "MMM dd, yyyy") : ""
        }
        checkOutDate={
          cart.visitDate ? format(new Date(cart.visitDate), "MMM dd, yyyy") : ""
        }
        guestName={fullName}
        isProcessing={processing}
      />
    </>
  );
}
